#ifndef YM3012_H
#define YM3012_H

#include <stdbool.h>
#include <stdint.h>

/* ---- ピン割り当て ------------------------------------------------------ */

/* SO / φ1 / SH1 / SH2 は PIO の in_base から連続していること */
#define YM3012_PIN_SO   17 /* シリアルデータ */
#define YM3012_PIN_PHI1 18 /* ビットクロック（φM/2） */
#define YM3012_PIN_SH1  19 /* CH2 のサンプルホールド。フレーム同期に使う */
#define YM3012_PIN_SH2  20 /* CH1 のサンプルホールド。現在は未使用 */

/*
 * ループバック自己診断で使うピン。GP26-GP28 を起動時の一瞬だけ CPU から叩いて
 * 合成フレームを流し込む。
 *
 * この 3 本は I2S 出力 (BCK / LRCK / DIN) と同じなので、I2S が有効なときは
 * 診断を行わない。診断だけ試すときは DAC を外して -DYM3012_LOOPBACK=1 で
 * 再コンフィグする。
 */
#ifndef YM3012_LOOPBACK_ENABLED
#if I2S_ENABLED
#define YM3012_LOOPBACK_ENABLED 0
#else
#define YM3012_LOOPBACK_ENABLED 1
#endif
#endif
#ifndef YM3012_LOOPBACK_BASE
#define YM3012_LOOPBACK_BASE 26 /* +0=SO / +1=φ1 / +2=SH1 */
#endif

/* ---- リング ------------------------------------------------------------ */

/*
 * DMA のハードウェアリング機能を使うのでサイズは 2 の冪。
 * 1 フレーム (L+R) がちょうど 1 エントリ (32bit) なので、
 * 16KB = 4096 フレームで、φM 4MHz なら 62500Hz の 65.5ms 分になる。
 * φM を下げると一周時間は伸びる（3.579545MHz で 73.2ms）ので制約は緩む方向。
 */
#define YM3012_RING_BITS   14u
#define YM3012_RING_BYTES  (1u << YM3012_RING_BITS)
#define YM3012_RING_FRAMES (YM3012_RING_BYTES / 4u)

/* ---- PCM 変換 ---------------------------------------------------------- */

/*
 * YM3012 の 16bit ワード 1 個を signed 16bit PCM へ変換する。
 *
 * ワードの中身は受信順に「無効 3bit / 仮数 D0..D9 / 指数 S0..S2」。PIO が右シフトで
 * 詰めるので、bit0..2 が無効、bit3..12 が仮数、bit13..15 が指数になる。
 *
 * データシート LSI-2130123 (1992-04) より:
 *   - 仮数は 10bit オフセットバイナリ。符号付き値は m - 512（範囲 -512..+511）
 *   - 指数は E = S2*4 + S1*2 + S0。E が大きいほどステップが粗い（E=1 が最も細かい）
 *   - 線形値は pcm = (m - 512) << (E - 1)
 *   - E = 0 は 3→7 デコーダの禁止コードで正常な出力には現れない。0 として扱う
 *
 * 値域は -32768 (m=0, E=7) 〜 +32704 (m=1023, E=7 = 511<<6)。
 * 正側が +32767 に届かないのは仕様どおりで、正規化してはいけない。
 */
static inline int16_t ym3012_word_to_pcm(uint16_t w) {
    uint32_t m = ((uint32_t)w >> 3) & 0x3ffu;
    uint32_t e = ((uint32_t)w >> 13) & 0x7u;

    if (e == 0u) {
        return 0;
    }

    /*
     * 負値の左シフトは未定義動作なので符号なしでシフトしてから型を戻す。
     * 結果は必ず -32768..+32704 に収まるので、切り捨ては起きない。
     */
    uint32_t v = ((uint32_t)m - 512u) << (e - 1u);
    return (int16_t)(uint16_t)v;
}

/* 1 フレーム (32bit) を L / R へ分解する。下位 16bit が L、上位 16bit が R。 */
static inline void ym3012_frame_to_pcm(uint32_t frame, int16_t *l, int16_t *r) {
    *l = ym3012_word_to_pcm((uint16_t)frame);
    *r = ym3012_word_to_pcm((uint16_t)(frame >> 16));
}

/* ---- 初期化 ------------------------------------------------------------ */

/*
 * PIO と DMA を起動する。以後キャプチャは常時動作し、停止しない。
 * 内部でループバック自己診断を 1 回実施する（DMA 開始前）。
 */
void ym3012_init(void);

bool ym3012_selftest_passed(void);       /* ループバック自己診断の結果 */
const char *ym3012_selftest_detail(void); /* 失敗時の内訳。成功なら "PASS" */

/* ---- リング操作 -------------------------------------------------------- */

/*
 * DMA の書き込み位置を読み、内部の総フレーム数を更新する。
 * リングが一周する 65.5ms より十分短い間隔で呼ぶこと（メインループから毎周回）。
 */
void ym3012_ring_poll(void);

/*
 * 65.5ms を超えて止まったあと（フラッシュの消去・書き込みなど）に呼ぶ。
 * ym3012_ring_poll() の差分はリング長で剰余を取るため、一周を超えた停止のあとに
 * そのまま呼ぶと総フレーム数に恒久的なずれが残る。ここで基準点を張り直し、
 * 既定カーソルを現在の書き込み位置へ合わせる。
 */
void ym3012_ring_resync(void);

/* DMA が書いた総フレーム数。p 0 のドレイン範囲を決めるスナップショットに使う。 */
uint64_t ym3012_write_total(void);

/* ---- 読み出しカーソル -------------------------------------------------- */

/*
 * リングの読み出し位置。消費者ごとに 1 個持つ。
 * 現在は USB キャプチャ（既定カーソル）と I2S 出力の 2 つが独立に読んでいる。
 *
 * count_forbidden は禁止コード E=0 を統計へ数えるかどうか。これは
 * 「キャプチャしたデータの品質」の指標なので、数えるのは既定カーソルだけにする。
 */
typedef struct {
    uint64_t read_total;
    bool count_forbidden;
} ym3012_reader_t;

/* 読み出し位置を現在の書き込み位置へ合わせて使い始める */
void ym3012_reader_init(ym3012_reader_t *rd, bool count_forbidden);

/* 未処理フレーム数。YM3012_RING_FRAMES 以上なら overrun。 */
uint32_t ym3012_reader_unread(const ym3012_reader_t *rd);

/* 読み出し位置を現在の書き込み位置へ合わせる（未処理を 0 にする） */
void ym3012_reader_sync(ym3012_reader_t *rd);

/* このカーソルが処理した総フレーム数 */
uint64_t ym3012_reader_read_total(const ym3012_reader_t *rd);

/*
 * 未処理フレームを最大 max_frames 個 PCM へ変換して out へ書く。
 * out は int16_t が 2 * max_frames 個入る大きさが必要。
 * 戻り値は実際に変換したフレーム数で、リング末尾をまたぐ場合はそこで切る。
 * 読み出し位置は変換した分だけ進む。
 */
uint32_t ym3012_reader_read_pcm(ym3012_reader_t *rd, int16_t *out, uint32_t max_frames);

/* ---- ミキサフック ------------------------------------------------------ */

/*
 * 変換した PCM に別の音源を混ぜるためのフック。
 *
 * ym3012_reader_read_pcm() の変換直後に呼ばれる。カーソルは消費者ごとに
 * 独立していて読み出し位置も違うが、first_frame は消費者によらない絶対
 * フレーム番号なので、フレーム番号で引ける音源を用意すれば、どのカーソルから
 * 何フレーム単位で読まれても同じ結果を返せる（= 冪等でよい）。
 *
 * inout は L/R 交互の frames 組。加算して飽和させるところまでフック側で行う。
 * 禁止コード E=0 の計数は混ぜる前に済ませているので、統計は「取り込んだ信号の
 * 品質」のまま変わらない。
 */
typedef void (*ym3012_mixer_t)(uint64_t first_frame, uint32_t frames, int16_t *inout);

/* NULL で解除。登録できるのは 1 個だけ。 */
void ym3012_set_mixer(ym3012_mixer_t fn);

/* ---- 出力ゲイン（フェードアウト）-------------------------------------- */

/*
 * ミキサの後段に掛ける出力ゲイン。1.0 から 0.0 へ frames かけて落とす。
 *
 * **ゲインは絶対フレーム番号の関数**にしてある。カーソルは I2S と USB キャプチャで
 * 2 本あり読み出し位置も読む量も違うので、経過時刻で決めると 2 本で違う音になる。
 * ミキサフックが first_frame を受けているのと同じ理屈（上のコメント）。
 *
 * カーブは残り比 q の 2 乗。線形だと終わり際で急に消えるように聞こえる。
 *
 * **効くのは I2S 出力と USB キャプチャだけ**で、YM3012 のアナログ出力には効かない。
 * こちらは OPM から DAC への経路をただ傍受しているだけで、間に入っていない。
 * 音を本当に止めるのは、フェードが終わったあとの停止（キーオフ）の方。
 */
void ym3012_fade_start(uint64_t start_frame, uint32_t frames);

/*
 * ゲインを 1.0 に戻す。冪等。
 *
 * 戻るのは**これから取り込むフレームから**で、リングに残っている分は落とし切った
 * ままにする。即座に戻すと、消費者がまだ読んでいないフェード済みの区間が全音量で
 * 出てしまい、曲の切り替わりで音が跳ねる。
 *
 * 境界は ym3012_ring_poll() を呼んで引き直してから置く。呼び出し側が
 * service_all() の音声チェーン（500us 間隔）を待つ必要は無い。
 */
void ym3012_fade_clear(void);

/*
 * ミキサが用意し終えたフレーム番号を伝える。カーソルはここを超えて読まない。
 *
 * ミキサ側は 1 フレームずつ描くと 1 回あたりの固定費が効いてしまうので、ある程度
 * まとめて描く。まとめている途中のフレームを消費者が先に持って行くと、その分だけ
 * 混ぜ損ねて音が途切れるため、読み出しの側で待たせる。I2S は 1024 フレームの
 * 先行を持っているので、数十フレーム待たせても余裕には響かない。
 */
void ym3012_set_mix_ready(uint64_t frame);

/* ---- 既定カーソル（USB キャプチャ用）---------------------------------- */

uint32_t ym3012_unread(void);
void ym3012_ring_sync(void);
uint64_t ym3012_read_total(void);
uint32_t ym3012_read_pcm(int16_t *out, uint32_t max_frames);

/* PIO の RX FIFO あふれを検出してクリアする。あふれていたら true。 */
bool ym3012_check_rxstall(void);

/* ---- 自己テスト -------------------------------------------------------- */

/*
 * PCM 変換の単体テスト。既知のワードに対する期待値を突き合わせる。
 * 失敗したら detail に最初の不一致の内容を書いて false を返す。
 */
bool ym3012_pcm_selftest(const char **detail);

#endif /* YM3012_H */
