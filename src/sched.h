#ifndef SCHED_H
#define SCHED_H

/*
 * USB・キャプチャ・I2S・LED・統計をひと回しする。
 *
 * コマンドの待ち時間（`d` の遅延や `p 0` のドレイン待ち）の中からも呼ぶので、
 * 待っている間も PCM の送出・I2S への供給・USB の処理が止まらない。
 * `vgm list` / `mdx list` / `autoplay list` の行出力の合間と、起動時のボタン
 * 解放待ちへは `void (*tick)(void)` としてこの関数そのものを渡す。
 *
 * **再入してはならないものをここから呼ばないこと。** コマンド処理中の待ちから
 * 呼ばれる以上、ここから上位の操作（autoplay / storage）へ降りると
 * `filelist_collect()` の走査バッファを壊し、コマンドの応答の途中へ別の出力が
 * 割り込む。ボタンは取り込みだけをここで行い、消化は `main()` の `for(;;)`
 * 直下の `button_dispatch()` が行う。
 *
 * CPU 使用率は「サービス関数の中に居た時間」をそのまま積む。サービスは連続して
 * 呼ばれるので区間は 1 本で足りる。何もする事が無い周回はどれもすぐ返るので
 * 自然に 0 に近づき、USB の空き待ちで送れなかった周回も CPU としては数えない。
 * tud_task() は毎周回走る固定費でどのサービスの負荷でもないので、別に集計する。
 *
 * 各グループを回す最短間隔と、その決め手は sched.c の *_INTERVAL_US にある。
 */
void service_all(void);

#endif /* SCHED_H */
